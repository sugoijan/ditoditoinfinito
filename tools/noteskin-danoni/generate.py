#!/usr/bin/env python3
"""Adapt the pinned, unmodified DanOni alpha masks to the game's static SVG subset.

Run: python3 tools/noteskin-danoni/generate.py [--check]
CSS mask images use alpha, irrespective of the original black RGB. Flatten their
class rules into presentation attributes and make the nontransparent pixels white
so Lua can tint them. 500-unit geometry and strokes are left untouched; 50 DanOni
pixels become one 64-unit noteskin lane. No rasterization or path approximation.
"""
import argparse
import re
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
OUT = ROOT / "assets/noteskins/dance/DanOni"


def convert(name):
    svg = ET.fromstring((HERE / "upstream/img" / name).read_text())
    style = next(svg.iter("{http://www.w3.org/2000/svg}style")).text
    rules = {}
    for selectors, body in re.findall(r"([^{}]+)\{([^{}]+)\}", style):
        attrs = dict(item.split(":", 1) for item in body.rstrip(";").split(";"))
        for selector in selectors.split(","):
            rules.setdefault(selector.strip().lstrip("."), {}).update(attrs)
    children = []
    for node in svg:
        tag = node.tag.split("}")[-1]
        if tag == "defs":
            continue
        attrs = rules.get(node.attrib.pop("class", ""), {}).copy()
        attrs.update(node.attrib)
        # SVG defaults to a black fill. Preserve fill:none; whiten all alpha.
        attrs["fill"] = "none" if attrs.get("fill") == "none" else "#ffffff"
        if "stroke" in attrs:
            attrs["stroke"] = "#ffffff"
        children.append("<" + tag + " " + " ".join(f'{k}="{v}"' for k, v in attrs.items()) + "/>")
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 500 500">\n'
            '<!-- Generated by tools/noteskin-danoni/generate.py from tickle’s MIT-licensed alpha mask. -->\n'
            + "\n".join(children) + "\n</svg>\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = {}
    for source, dest in [("arrow.svg", "_arrow shape.svg"), ("onigiri.svg", "_onigiri shape.svg"),
                         ("arrowShadow.svg", "_arrow shadow.svg"), ("aaShadow.svg", "_onigiri shadow.svg")]:
        generated[dest] = convert(source)
    # makeFrzSprites / changeHitFrz: 40/50-wide strip, same alpha in both states.
    for state, color, alpha in [("inactive", "#6600ff", 0.75), ("active", "#999933", 0.75),
                                ("dropped", "#999999", 1)]:
        generated[f"_bar {state}.svg"] = (
            '<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64" viewBox="0 0 50 50">\n'
            '<!-- Generated by tools/noteskin-danoni/generate.py from DanOni freeze-bar constants. -->\n'
            f'<rect x="5" width="40" height="50" fill="{color}" fill-opacity="{alpha}"/>\n</svg>\n')
    for dest, text in generated.items():
        path = OUT / dest
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f"Stale generated art: {path}")
        else:
            path.write_text(text)


if __name__ == "__main__":
    main()
