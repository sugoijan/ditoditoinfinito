"""Regenerate the CPU timing grid and uniform-bin Wife reward means.

Development dependencies: numpy, scipy and rustfmt. No model, chart corpus or
research code is needed. The generated Rust constants have no runtime dependency.
"""
from pathlib import Path
import math
import subprocess
import numpy as np
from scipy.integrate import quad


def wife(delta):
    """Normalized Wife-style timing reward used only for the analytical anchor."""
    ms = abs(delta) * 1000
    if ms <= 5:
        return 1.
    if ms > 180:
        return -2.75
    if ms > 65:
        return -2.75 * (ms - 65) / 115
    x = (65 - ms) / 22.7
    t = 1 / (1 + .3275911 * abs(x))
    p = (((((1.061405429 * t - 1.453152027) * t) + 1.421413741) * t - .284496736) * t + .254829592) * t
    return np.sign(x) * (1 - p * math.exp(-x*x))


root = Path(__file__).resolve().parents[2]
coarse = [-.18, -.135, -.09, -.045, -.0225, -.005, .005, .0225, .045, .09, .135, .18]
# Preserve nested subdivision arithmetic for reproducible floating-point edges.
original = np.r_[np.concatenate([np.linspace(a, b, 5)[:-1] for a, b in zip(coarse[:-1], coarse[1:])]), coarse[-1]]
edges = np.sort(np.r_[original, (original[:-1] + original[1:]) / 2])
means = []
for lo, hi in zip(edges[:-1], edges[1:]):
    points = [v for v in [-.065, -.005, .005, .065] if lo < v < hi]
    means.append(quad(wife, lo, hi, points=points, epsabs=1e-12)[0] / (hi-lo))
rewards = np.r_[means, [-2.75]*3]
text = '// Generated by tools/cpu-player/export_basis.py; timing grid and Wife means.\n'
text += 'pub(super) const EDGES: [f64; 89] = ' + repr(edges.tolist()) + ';\n'
text += 'pub(super) const REWARDS: [f64; 91] = ' + repr(rewards.tolist()) + ';\n'
path = root / 'crates/engine/src/cpu/basis.rs'
path.write_text(text)
subprocess.run(['rustfmt', '--edition', '2024', str(path)], check=True)
