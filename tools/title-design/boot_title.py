#!/usr/bin/env python3
"""The web page's loader's art data (`site/boot-art-data.js`, inlined
into `site/index.html` before `site/boot-art.js`, which draws it): the
shaped Dosis lettering of `geometry.js` as path data small enough for
the page to stay within the first round trip (`xtask check-boot`), with
Infinito's palette and the menu rain's outlines (`assets/ui/menu-rain.svg`).

Each distinct outline is one path, named `a` on (seven for fifteen
glyphs; the fi is a ligature), placed wherever the letter recurs, its
coordinates at one decimal of the 96-unit capital; each glyph's bounds
and which glyphs are the initials go with them, so that boot-art.js can
cut the rings and the clearance as the atlas does (generate.py) and
center each initial's field as the game does (wordmark_geometry.rs).

Run by generate.py; alone: python3 tools/title-design/boot_title.py
"""
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
PAD = 38


def number(v):
    return f"{v:.1f}".rstrip("0").rstrip(".")


def normalize(path, left, top):
    """`path` moved so its bounds' corner is the origin, one decimal."""
    out, cmd, axis = [], "", 0
    for tok in re.findall(r"[A-Za-z]|-?\d+(?:\.\d+)?", path):
        if tok.isalpha():
            cmd, axis = tok, 0
            out.append(tok)
            continue
        v = float(tok)
        if cmd == "H":
            v -= left
        elif cmd == "V":
            v -= top
        else:
            v -= left if axis == 0 else top
            axis ^= 1
        out.append(number(v))
    s = ""
    for tok in out:
        if s and not tok.isalpha() and not s[-1].isalpha() and not tok.startswith("-"):
            s += " "
        s += tok
    return s


def shapes_and_uses(glyphs):
    """The distinct outlines (id, path) and each glyph's (id, x, y)."""
    shapes, known, uses = [], [], []
    for g in glyphs:
        left, top = g["bounds"][0], g["bounds"][1]
        path = normalize(g["path"], left, top)
        toks = re.findall(r"[A-Za-z]|-?\d+(?:\.\d+)?", path)
        nums = [float(t) for t in toks if not t.isalpha()]
        cmds = "".join(t for t in toks if t.isalpha())
        # The same glyph's outlines differ by rounding noise only.
        hit = next((k for n, c, k in known
                    if c == cmds and len(n) == len(nums)
                    and all(abs(a - b) < 0.15 for a, b in zip(n, nums))), None)
        if hit is None:
            hit = chr(ord("a") + len(known))
            known.append((nums, cmds, hit))
            shapes.append([hit, path])
        uses.append([hit, round(left, 1), round(top, 1)])
    return shapes, uses


def rain():
    """The rain atlas's two outlines and its rows' stroke widths."""
    svg = (ROOT / "assets/ui/menu-rain.svg").read_text()
    paths = dict(re.findall(r'<path id="(\w+)" d="([^"]*)"', svg))
    weights = [float(w) for w in re.findall(r'translate\(0 \d+\)[^>]*stroke-width="([^"]*)"', svg)]
    assert len(weights) == 8, weights
    return paths["arrow"], paths["onigiri"], weights


def art_data(data):
    title, palette = data["title"], data["palette"]
    glyphs = title["glyphs"]
    shapes, uses = shapes_and_uses(glyphs)
    arrow, onigiri, weights = rain()
    out = {
        "glyphs": shapes,
        "uses": uses,
        "bounds": [[round(v, 1) for v in g["bounds"]] for g in glyphs],
        "initials": [i for i, g in enumerate(glyphs) if g["initial"]],
        "title": {"w": round(title["width"] + 2 * PAD, 1), "h": title["height"] + 2 * PAD},
        "pad": PAD,
        "palette": palette,
        "arrow": arrow,
        "onigiri": onigiri,
        "weights": weights,
    }
    return ("// Generated by tools/title-design/boot_title.py: the loader's title and rain (boot-art.js).\n"
            "window.__DDI_ART_DATA=" + json.dumps(out, separators=(",", ":")) + ";\n")


def main():
    js = (HERE / "geometry.js").read_text()
    data = json.loads(js[js.index("{"):js.rindex("}") + 1])
    (ROOT / "site/boot-art-data.js").write_text(art_data(data))


if __name__ == "__main__":
    main()
