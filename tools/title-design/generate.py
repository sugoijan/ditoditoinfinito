#!/usr/bin/env python3
"""Shape the title and extract Infinito's palette; no font installation needed.

Requires fonttools==4.67.0 and uharfbuzz==0.57.0.
"""

import io
import json
from pathlib import Path
import xml.etree.ElementTree as ET

import uharfbuzz as hb
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]


def shape(file, axes, text, height):
    font = instantiateVariableFont(TTFont(HERE / "fonts" / file), axes)
    data = io.BytesIO()
    font.save(data)
    hb_font = hb.Font(hb.Face(data.getvalue()))
    buffer = hb.Buffer()
    buffer.add_str(text)
    buffer.guess_segment_properties()
    hb.shape(hb_font, buffer)
    glyphs = font.getGlyphSet()
    order = font.getGlyphOrder()
    cap = font["OS/2"].sCapHeight
    scale = height / cap
    x = 12.0
    shaped = []
    for info, position in zip(buffer.glyph_infos, buffer.glyph_positions):
        glyph = glyphs[order[info.codepoint]]
        transform = (scale, 0, 0, -scale,
                     x + position.x_offset * scale,
                     height + 12 - position.y_offset * scale)
        pen = SVGPathPen(glyphs, ntos=lambda n: format(n, ".3f").rstrip("0").rstrip("."))
        bounds = BoundsPen(glyphs)
        glyph.draw(TransformPen(pen, transform))
        glyph.draw(TransformPen(bounds, transform))
        if bounds.bounds:
            shaped.append({"path": pen.getCommands(), "bounds": bounds.bounds,
                           "initial": info.cluster in (0, 5, 10)})
        x += position.x_advance * scale
    return {"glyphs": shaped, "width": x + 12, "height": height + 28}


def generate_atlas(data):
    # Four equally sized rows: the protected D/D/I outlines, then the letters.
    # Keep the study's maximum padding so its field coordinates match exactly.
    title = data["title"]
    padding, gap, outline = 38, 12, 12
    width = title["width"] + padding * 2
    height = title["height"] + padding * 2
    initials = [g for g in title["glyphs"] if g["initial"]]
    paths = "".join(f'<path d="{g["path"]}"/>' for g in title["glyphs"])
    protection = (
        f'<mask id="clear" maskUnits="userSpaceOnUse" x="-{padding}" '
        f'y="-{padding}" width="{width}" height="{height}">'
        f'<rect x="-{padding}" y="-{padding}" width="{width}" '
        f'height="{height}" fill="white"/>'
        f'<g fill="black" stroke="black" stroke-width="{gap * 2}" '
        f'stroke-linejoin="round">{paths}</g></mask>'
    )
    rows = []
    for i in range(4):
        if i == 3:
            art = f'<g fill="white">{paths}</g>'
        else:
            art = (
                f'<g mask="url(#clear)"><path d="{initials[i]["path"]}" '
                f'fill="white" stroke="white" stroke-width="{(gap + outline) * 2}" '
                'stroke-linejoin="round"/></g>'
            )
        rows.append(f'<g transform="translate({padding},{i * height + padding})">{art}</g>')
    (HERE / "atlas.svg").write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width * 2}" '
        f'height="{height * 8}" viewBox="0 0 {width} {height * 4}">'
        f'<defs>{protection}</defs>' + "".join(rows) + "</svg>\n"
    )
    fields = []
    for glyph in initials:
        left, top, right, bottom = glyph["bounds"]
        cx, cy = (left + right) / 2, (top + bottom) / 2
        fields.append([
            (-padding - cx) * 2 / 3, (-padding - cy) * 2 / 3,
            (width - padding - cx) * 2 / 3, (height - padding - cy) * 2 / 3,
        ])
    rust = "// Generated by tools/title-design/generate.py. Dosis 800; outline/gap 12/12.\n"
    rust += f"pub const ASPECT: f32 = {width / height:.7g};\n"
    rust += "pub const FIELDS: [[f32; 4]; 3] = [\n"
    rust += "".join("    [" + ", ".join(f"{v:.7g}" if v % 1 else f"{v:.1f}" for v in row) + "],\n" for row in fields)
    rust += "];\n"
    (ROOT / "crates/theme/src/wordmark_geometry.rs").write_text(rust)


def main():
    title = shape("Dosis.ttf", {"wght": 800}, "Dito Dito Infinito", 96)
    ui = shape("Inconsolata.ttf", {"wdth": 100, "wght": 400},
               "Singleplayer   Options   Credits", 12)
    source = ROOT / "assets/noteskins/dance/Infinito/_spiral components.svg"
    tree = ET.parse(source)
    gradient = tree.find(".//*[@id='palette']")
    palette = [stop.attrib["stop-color"] for stop in gradient]
    data = {"title": title, "ui": ui, "palette": palette}
    generate_atlas(data)
    (HERE / "geometry.js").write_text(
        "// Generated by generate.py: Dosis 800, Inconsolata 400, Infinito palette.\n"
        "window.DDI_TITLE = " + json.dumps(data, separators=(",", ":")) + ";\n")
    (HERE / "preview-markup.js").write_text(
        "// Generated from preview.html by generate.py.\n"
        "document.getElementById('study').innerHTML = "
        + json.dumps((HERE / "preview.html").read_text()) + ";\n")


if __name__ == "__main__":
    main()
